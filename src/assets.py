"""
Asset loader — serves pre-generated PNG sprites/textures from assets/.

Key feature: compose_player(player, direction) builds a layered character
sprite by compositing DCSS body/head/weapon/shield/boots/gloves overlays
on top of the base figure, cached by equipment fingerprint + direction.
Falls back silently to the plain base sprite when overlays are absent.

Usage:
    from src.assets import assets
    spr = assets.compose_player(player, "south")  # layered, equipment-aware
    spr = assets.enemy("goblin")
    tex = assets.tile("floor", "dungeon", variant=0)
    spr = assets.item_sprite("Broad Sword")
"""
